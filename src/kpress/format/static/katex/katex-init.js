// KaTeX progressive enhancement. Vendored KaTeX (katex.min.js) and its
// auto-render extension (auto-render.min.js) load before this script. The
// server emits each expression as a TeX source node (.kpress-math-render)
// plus a semantic MathML node (.kpress-math-semantic). KaTeX renders the TeX
// in place; the MathML stays in the accessibility tree as the no-JS fallback.
//
// This loads as a classic deferred <script> (after the UMD KaTeX globals), so it
// is a self-invoking IIFE-style script -- no ESM `export` (that would throw
// "Unexpected token 'export'" in a classic script and skip math enhancement).

const OPTIONS = {
  delimiters: [
    { left: "\\[", right: "\\]", display: true },
    { left: "\\(", right: "\\)", display: false },
  ],
  throwOnError: false,
  ignoredClasses: ["kpress-math-semantic"],
};

// Math text face (katex/katex-text-face.css): the `KPress Math Text` composite
// draws Latin letters and digits from the reading face and leaves the rest to
// KaTeX. KaTeX lays out from a metric table baked into its own bundle, so
// without this the boxes would be measured for Computer Modern and drawn in PT
// Serif -- wrong fraction widths, script positions and italic corrections.
// katex-text-metrics.js (generated by devtools/katex_text_metrics.py, loaded
// just before this script) defines the replacement tables on
// `globalThis.kpressKatexTextMetrics`, keyed by KaTeX face name plus a `scale`
// entry that belongs to the stylesheet's `size-adjust`, not to KaTeX.
//
// The tables are one setting for the whole page: `__setFontMetrics` replaces a
// table in the KaTeX singleton, so a page cannot lay out one document with the
// reading face's numbers and another with Computer Modern's. The decision is
// therefore taken over every math host on the page, under the same three
// opt-outs the stylesheet honours on any ancestor: `data-kpress-math-text="katex"`,
// `data-kpress-fonts="system"` and the reader's persisted
// `data-kpress-font-set="system"`. A page that mixes opted-in and opted-out
// hosts is unsupported; the metrics follow the opted-in ones.
//
// If a host wants the face and the tables cannot be applied -- the asset did not
// load, or a KaTeX bump renamed its private setter -- the face is turned off as
// well, by stamping the opt-out on <html>, which the stylesheet reads. Faces
// without metrics is the one state the design forbids.
const TEXT_FACE_OPT_OUT =
  '[data-kpress-math-text="katex"], [data-kpress-fonts="system"], [data-kpress-font-set="system"]';
let metricsApplied = false;

function applyTextMetrics(nodes) {
  if (metricsApplied) {
    return;
  }
  let wanted = false;
  for (const node of nodes) {
    if (!node.closest(TEXT_FACE_OPT_OUT)) {
      wanted = true;
      break;
    }
  }
  if (!wanted) {
    return;
  }
  metricsApplied = true;
  const metrics = globalThis.kpressKatexTextMetrics;
  const katex = globalThis.katex;
  const install = katex?.__setFontMetrics;
  if (!metrics || typeof metrics !== "object" || typeof install !== "function") {
    document.documentElement.dataset.kpressMathText = "katex";
    console.warn(
      "kpress: the math text face metrics are unavailable; KaTeX's own faces are restored",
    );
    return;
  }
  for (const [face, table] of Object.entries(metrics)) {
    if (face === "scale") {
      continue;
    }
    install.call(katex, face, table);
  }
}

function enhanceMath() {
  const render = globalThis.renderMathInElement;
  if (typeof render !== "function") {
    return;
  }
  const nodes = document.querySelectorAll(".kpress-math-render");
  applyTextMetrics(nodes);
  for (const node of nodes) {
    const host = node.closest("[data-kpress-math]");
    if (!host || host.dataset.kpressMathRendered === "true") {
      continue;
    }
    try {
      render(node, OPTIONS);
      host.dataset.kpressMathRendered = "true";
    } catch {
      // Leave the semantic MathML fallback in place on failure.
    }
  }
}

// PAINTING ONCE. KaTeX renders into the live DOM, so an expression is painted
// the moment it is rendered, in whatever faces have decoded by then. The
// composite's reading-face slots are separate @font-face rules from the prose
// PT Serif, fetched only when a formula first asks for them, so a render that
// starts before they are ready paints the letters and digits in the next family
// of the stack (KaTeX_Main) and repaints them when the slot arrives -- which a
// reader sees as the digits in every formula changing font. Measured on a
// twenty-formula page over loopback: the first `.katex` node was inserted at
// 70ms and the composite's slots decoded between 111ms and 116ms; with 150ms of
// latency added, at 817ms against 851ms and 1009ms.
//
// So the faces the mathematics will use are loaded first, and the render waits
// on them. The same page then inserts its first expression at 129ms, after
// every face. Where the page inlines its fonts as data URIs the wait costs tens
// of milliseconds; in hosted mode it delays the mathematics by a font round trip
// instead of flashing it, which is the right trade for a reading page and the
// same one `font-display: block` makes in katex-text-face.css.

// Sample text for `document.fonts.load()`, which loads a face only when the
// text has a code point the face's `unicode-range` covers. It therefore has to
// reach both faces of every composite slot: `a` for the reading face's Latin
// range, `1` for its digits, `Ω` for the upright slots' Greek (U+0391-03A9,
// capitals only) and `α` for the italic slots' (U+0370-03FF).
const FACE_SAMPLE = "a1αΩ";

// The composite's four slots, as CSS `font` shorthands. All four, because which
// expression first asks for `\mathbf` or `\boldsymbol` is not knowable before
// the render; the reading-face halves name the same woff2 files as the prose
// faces, so a page whose prose already uses PT Serif bold or italic pays no
// extra request for them.
const TEXT_FACE_FONTS = [
  "400 1em 'KPress Math Text'",
  "italic 400 1em 'KPress Math Text'",
  "700 1em 'KPress Math Text'",
  "italic 700 1em 'KPress Math Text'",
];

// The KaTeX faces to wait on in either mode. `KaTeX_Main` and `KaTeX_Math` are
// the families every rule in katex-text-face.css names after the composite --
// where operators, relations, punctuation and everything the composite leaves
// unclaimed are drawn -- and the ones that draw the letters and digits as well
// when the face is off. The construct-specific families (AMS, Size1-4,
// Caligraphic, Fraktur, Script, SansSerif, Typewriter) declare no
// `unicode-range`, so any sample matches them and waiting on them would fetch
// all thirteen on every page with math; they keep the bundle's own `swap`.
const KATEX_FONTS = [
  "400 1em 'KaTeX_Main'",
  "italic 400 1em 'KaTeX_Main'",
  "700 1em 'KaTeX_Main'",
  "italic 700 1em 'KaTeX_Main'",
  "italic 400 1em 'KaTeX_Math'",
  "italic 700 1em 'KaTeX_Math'",
];

// How long the wait may last, matching the block period `font-display: block`
// gives a face before it swaps anyway: past it the wait buys nothing, and
// mathematics that never appears is worse than mathematics that repaints.
const FACE_WAIT_MS = 3000;

/**
 * The faces this page's mathematics will be drawn from, as `document.fonts.load`
 * promises, or `null` when there is nothing to wait for: no math, no KaTeX to
 * render it, or no font loading API -- a browser without `document.fonts` has no
 * `font-display` either, and renders exactly as it did before.
 *
 * @returns {Promise<unknown>[] | null}
 */
function mathFaceLoads() {
  const fonts = document.fonts;
  const nodes = document.querySelectorAll(".kpress-math-render");
  if (
    nodes.length === 0 ||
    typeof globalThis.renderMathInElement !== "function" ||
    !fonts ||
    typeof fonts.load !== "function"
  ) {
    return null;
  }
  const specs = [...KATEX_FONTS];
  for (const node of nodes) {
    // The composite is only reachable where the stylesheet applies it, so a page
    // that has opted out waits on the KaTeX faces alone.
    if (!node.closest(TEXT_FACE_OPT_OUT)) {
      specs.push(...TEXT_FACE_FONTS);
      break;
    }
  }
  return specs.map((spec) => fonts.load(spec, FACE_SAMPLE));
}

function startMath() {
  const loads = mathFaceLoads();
  if (loads === null) {
    enhanceMath();
    return;
  }
  const deadline = new Promise((resolve) => setTimeout(resolve, FACE_WAIT_MS));
  // Both handlers render: a face that fails to load must not take the
  // mathematics with it.
  Promise.race([Promise.all(loads), deadline]).then(enhanceMath, enhanceMath);
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", startMath, { once: true });
} else {
  startMath();
}
