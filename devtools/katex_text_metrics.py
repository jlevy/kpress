"""Generate the KaTeX metric tables the math text face lays out from.

KaTeX lays out from a metric table baked into its bundle: per face and code point,
``[depth, height, italic, skew, width]`` in em. The math text face draws Latin letters
and digits from the reading face instead of the KaTeX faces, so for those code points
the baked table no longer describes the glyphs on screen, and it also keeps KaTeX's
Greek at a size that reads small beside PT Serif.

This tool rebuilds the six affected tables: swapped code points are re-measured from the
reading face's own outlines, Greek is scaled by a frozen per-face factor, and everything
else is carried over from KaTeX unchanged. The result is written to
``static/katex/katex-text-metrics.js`` as ``globalThis.kpressKatexTextMetrics``;
``katex-init.js`` applies it with ``katex.__setFontMetrics``, which replaces a face's
whole table and has no getter, so each table must be complete.

Run ``python -m devtools.katex_text_metrics`` to regenerate the asset, ``--check`` to
verify the shipped copy still matches its inputs, and ``--print-scale`` to print the
Greek scale factors the composite's ``size-adjust`` descriptors must equal.
"""

from __future__ import annotations

