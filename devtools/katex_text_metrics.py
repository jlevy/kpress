ROOT: Final = Path(__file__).resolve().parents[1]
STATIC: Final = ROOT / "src" / "kpress" / "format" / "static"
KATEX_BUNDLE: Final = STATIC / "katex" / "katex.min.js"
ASSET_PATH: Final = STATIC / "katex" / "katex-text-metrics.js"
FACE_CSS_PATH: Final = STATIC / "katex" / "katex-text-face.css"
READING_FONTS: Final = STATIC / "fonts"
KATEX_FONTS: Final = STATIC / "katex" / "fonts"

REGENERATE_COMMAND: Final = "uv run python -m devtools.katex_text_metrics"

# Public JS contract, mirrored by katex-init.js and the tests.
GLOBAL_NAME: Final = "kpressKatexTextMetrics"
SCALE_KEY: Final = "scale"
ASSET_HEADER: Final = (
    "/* GENERATED by devtools/katex_text_metrics.py — do not edit. Complete KaTeX metric"
    " tables for the faces the math text face swaps; applied by katex-init.js through"
    " katex.__setFontMetrics. */"
)

# KaTeX rounds its own table to five decimals, so five keeps the carried-over entries
# byte-identical to what the bundle ships and gives the re-measured ones the same
# resolution.
PRECISION: Final = 5

# Code points the composite family draws from the reading face.
DIGITS: Final = tuple(range(0x30, 0x3A))
LETTERS: Final = (*range(0x41, 0x5B), *range(0x61, 0x7B))
LETTERS_AND_DIGITS: Final = (*DIGITS, *LETTERS)

# Code points the Greek scale factor multiplies. The upright faces carry capitals only;
# the italic faces carry the lowercase alphabet and its variants as well.
UPRIGHT_GREEK: Final = tuple(range(0x391, 0x3AA))
ITALIC_GREEK: Final = tuple(range(0x370, 0x400))

# ---- Greek scale factors ----
#
# The reading face has no Greek, so KaTeX keeps it, and left alone it sits visibly small
# beside PT Serif. Each affected face is therefore scaled to the reading face's own
# vertical measure -- italic Greek to its x-height, upright capitals to its cap height --
# and every metric value in the Greek ranges is multiplied by the same factor so KaTeX
# lays out what the browser draws.
#
# Derived once from OS/2, rounded to three decimals, and frozen here as literals because
# the `size-adjust` descriptors in katex-text-face.css must equal them exactly. Nothing
# recomputes them at run time: `--print-scale` prints them, and `--check` re-derives them
# from the fonts and fails if a font bump has moved one.
#
#   face             reading face (per 1000 em)     KaTeX face                factor
#   Main-Regular     PT Serif cap 700             /  KaTeX_Main-Regular 683    1.025
#   Main-Bold        PT Serif cap 700             /  KaTeX_Main-Bold 686       1.020
#   Main-Italic      PT Serif Italic x 507        /  KaTeX_Main-Italic 442     1.147
#   Main-BoldItalic  PT Serif Bold Italic x 509   /  KaTeX_Main-BoldItalic 451 1.129
#   Math-Italic      PT Serif Italic x 507        /  KaTeX_Math-Italic 441     1.150
#   Math-BoldItalic  PT Serif Bold Italic x 509   /  KaTeX_Math-BoldItalic 452 1.126
#
# KaTeX_Math-BoldItalic is the one face whose OS/2 sxHeight is not its x-height: the
# table says 532 while every lowercase glyph in the face tops out at 452, and 532 would
# shrink the Greek instead of growing it. `_vertical_measure` cross-checks OS/2 against
# the ink height of the reference glyph and prefers the ink when the two disagree by more
# than OS2_INK_TOLERANCE, which is where 452 comes from.
MAIN_REGULAR_SCALE: Final = 1.025
MAIN_BOLD_SCALE: Final = 1.020
MAIN_ITALIC_SCALE: Final = 1.147
MAIN_BOLD_ITALIC_SCALE: Final = 1.129
MATH_ITALIC_SCALE: Final = 1.150
MATH_BOLD_ITALIC_SCALE: Final = 1.126

# Ink-versus-OS/2 disagreement, in em, past which the ink height wins.
OS2_INK_TOLERANCE: Final = 0.02
X_HEIGHT_GLYPH: Final = "x"
CAP_HEIGHT_GLYPH: Final = "H"

MetricRow = tuple[float, float, float, float, float]
MetricTable = dict[int, MetricRow]


@dataclass(frozen=True)
class Glyph:
    """One glyph measured in KaTeX's own terms, in em.

    `italic` is the ink overhang past the advance, which is how KaTeX's extractor
    defines the italic correction.
    """

    depth: float
    height: float
    italic: float
    width: float


@dataclass(frozen=True)
class Face:
    """The parts of a woff2 face this tool measures."""

    x_height: float
    cap_height: float
    glyphs: Mapping[int, Glyph]


@dataclass(frozen=True)
class FacePlan:
    """How one KaTeX metric table is rebuilt."""

    katex_face: str
    """Table name in katex.min.js, and the key in the generated asset."""

    katex_font: str
    """The woff2 that face draws from; the Greek factor is derived against it."""

    reading_font: str
    """The woff2 the swapped code points are re-measured from."""

    swapped: tuple[int, ...]
    """Code points the composite family draws from the reading face."""

    greek: tuple[int, ...]
    """Code points the scale factor multiplies."""

    scale: float
    """Frozen Greek scale factor; see the derivation above."""

    reference_glyph: str
    """Glyph whose ink height the factor is measured from."""


PT_SERIF_REGULAR: Final = "pt-serif-latin-400-normal.woff2"
